r"""
create_Fdata_vars.py -- store the Legendre F_theta/F_phi functions in ADS.

Reads mathematica/tables/FTheta_ADS_Discrete.txt and FPhi_ADS_Discrete.txt
(BEGIN DSCRDATA ... END DSCRDATA, generated by LegendreFThetaFPhi.wl) and
creates SphericalHarmonics_lib:Ftheta_Fphi_vars with two Global-scope VAR
instances, VAR_Ftheta and VAR_Fphi, holding one expression per (l, m):
Ftheta_l{l}_m{m} and Fphi_l{l}_m{m} (negative m written "mneg{|m|}").
The expressions are functions of theta, supplied by the parent design.
The library is created if it does not exist.

lMax is taken from a "REM lMax=N" line if present, otherwise inferred from
the largest index i = l(l+1)+m = lMax(lMax+2).

Usage (ADS Python console, after start_console.py):
    run_script("create_Fdata_vars.py")

Requires the table files to use "theta" (not "th") in the formulas, as
written by the current LegendreFThetaFPhi.wl. The target cell is deleted and
rebuilt if it exists. Afterwards, check that both VARs have Global scope.
"""

from pathlib import Path
import re
import keysight.ads.de as de

# ==================== Configuration -- edit as needed ====================

# Repository folders (defined by start_console.py; derived here if this file is exec()'d directly).
try:
    SCRIPT_DIR
except NameError:
    SCRIPT_DIR = Path(THIS_SCRIPT_PATH).resolve().parent
DATA_DIR = SCRIPT_DIR.parents[1] / "mathematica" / "tables"
FTHETA_FILE = DATA_DIR / "FTheta_ADS_Discrete.txt"
FPHI_FILE = DATA_DIR / "FPhi_ADS_Discrete.txt"

LIBRARY_NAME = "SphericalHarmonics_lib"
CELL_NAME = "Ftheta_Fphi_vars"

# ============================================================================


def parse_dscrdata(filepath):
    """Parse a BEGIN DSCRDATA / END DSCRDATA file into {index: formula_str},
    also returning lMax if a 'REM lMax=N' comment line is present (None
    otherwise, in which case the caller should infer it -- see
    infer_lmax)."""
    data = {}
    lmax_header = None
    in_block = False
    with open(filepath, "r") as f:
        for raw_line in f:
            line = raw_line.strip()
            if not line:
                continue
            if line.upper().startswith("REM"):
                match = re.search(r"lMax\s*=\s*(\d+)", line, re.IGNORECASE)
                if match:
                    lmax_header = int(match.group(1))
                continue
            if line.upper().startswith("BEGIN"):
                in_block = True
                continue
            if line.upper().startswith("END"):
                in_block = False
                continue
            if line.startswith("%"):
                continue
            if in_block:
                parts = line.split()
                if len(parts) == 2:
                    idx_str, formula = parts
                    data[int(idx_str)] = formula
    return data, lmax_header


def infer_lmax(data, header_lmax):
    """Use the REM-header lMax if present; otherwise derive it from the
    largest index in the data. The largest index occurs at l=lMax,
    m=lMax: i_max = lMax(lMax+1)+lMax = lMax(lMax+2), so
    lMax = -1 + sqrt(1+i_max)."""
    if header_lmax is not None:
        return header_lmax
    if not data:
        raise ValueError("No data parsed; cannot infer lMax.")
    i_max = max(data.keys())
    l_max = round(-1 + (1 + i_max) ** 0.5)
    if l_max * (l_max + 2) != i_max:
        raise ValueError(
            f"Could not cleanly infer lMax from max index {i_max} -- "
            f"the data may not cover a full 0..lMax range."
        )
    return l_max


def index_to_lm_map(l_max):
    """Rebuild the i = l(l+1)+m -> (l,m) mapping used by the Wolfram export."""
    mapping = {}
    for l in range(0, l_max + 1):
        for m in range(-l, l + 1):
            i = l * (l + 1) + m
            mapping[i] = (l, m)
    return mapping


def var_name(prefix, l, m):
    """ADS-identifier-safe variable name, e.g. Ftheta_l1_mneg1, Ftheta_l1_m0."""
    m_part = f"mneg{abs(m)}" if m < 0 else f"m{m}"
    return f"{prefix}_l{l}_{m_part}"


def populate_var(var_inst, data, prefix, idx_to_lm):
    """Set var_inst.vars[name] = formula for every entry, then delete the
    default 'X' placeholder that a new VAR instance always starts with."""
    for i, formula in data.items():
        l, m = idx_to_lm[i]
        name = var_name(prefix, l, m)
        var_inst.vars[name] = formula
    del var_inst.vars["X"]


# ---- Parse the exported Discrete-format files ----
ftheta_data, ftheta_lmax_header = parse_dscrdata(FTHETA_FILE)
fphi_data, fphi_lmax_header = parse_dscrdata(FPHI_FILE)

L_MAX_ftheta = infer_lmax(ftheta_data, ftheta_lmax_header)
L_MAX_fphi = infer_lmax(fphi_data, fphi_lmax_header)

if L_MAX_ftheta != L_MAX_fphi:
    print(f"WARNING: inferred lMax differs between the F_theta file "
          f"({L_MAX_ftheta}) and F_phi file ({L_MAX_fphi}) -- using "
          f"{L_MAX_ftheta}. Check that both files came from the same "
          f"Wolfram export run.")

L_MAX = L_MAX_ftheta
idx_to_lm = index_to_lm_map(L_MAX)

print(f"Parsed {len(ftheta_data)} F_theta entries, {len(fphi_data)} F_phi "
      f"entries. Inferred lMax = {L_MAX} "
      f"({'from REM header' if ftheta_lmax_header is not None else 'from max index'}).")

# ---- Get the active workspace, create the library if it doesn't exist ----
ws = de.active_workspace()
print(f"Active workspace: {ws}")

if LIBRARY_NAME in ws.library_names:
    lib = ws.open_library(LIBRARY_NAME)
    print(f"Reusing existing library: {LIBRARY_NAME}")
else:
    lib_path = ws.path / LIBRARY_NAME
    lib = de.create_new_library(LIBRARY_NAME, lib_path)
    print(f"Created new library: {LIBRARY_NAME} at {lib_path}")

# ---- Create the schematic and the two VAR instances ----
# Rebuild: delete the cell first if it exists (create_schematic cannot
# overwrite a view, and delete_cell needs the cell's views closed).
if lib.cell_exists(CELL_NAME):
    print(f"Cell '{CELL_NAME}' already exists in '{LIBRARY_NAME}' -- deleting it first.")
    for view_name in ("schematic", "symbol"):
        try:
            de.db_uu.open_design((LIBRARY_NAME, CELL_NAME, view_name)).close_design()
        except Exception:
            pass
    lib.delete_cell(CELL_NAME)
design = de.db_uu.create_schematic((LIBRARY_NAME, CELL_NAME, "schematic"))

var_ftheta = design.add_instance(("ads_datacmps", "VAR", "symbol"), (0, 0), name="VAR_Ftheta", angle=90)
assert var_ftheta.is_var_instance

var_fphi = design.add_instance(("ads_datacmps", "VAR", "symbol"), (0, 3), name="VAR_Fphi", angle=90)
assert var_fphi.is_var_instance

with de.db_uu.Transaction(design) as transaction:
    # theta is not defined here; it comes from the parent design that
    # instantiates this cell (nested scope). The default "X" entry is removed.
    populate_var(var_ftheta, ftheta_data, "Ftheta", idx_to_lm)
    populate_var(var_fphi, fphi_data, "Fphi", idx_to_lm)

    # Global scope lets the parent design reference Ftheta_*/Fphi_*.
    # set_global_scope() does not always persist: check each VAR's Scope
    # in Component Options in the ADS GUI afterwards.
    var_ftheta.set_global_scope()
    var_fphi.set_global_scope()

    transaction.commit()

design.save_design()
print(f"Created {len(ftheta_data)} Ftheta variables in VAR_Ftheta and "
      f"{len(fphi_data)} Fphi variables in VAR_Fphi, in {LIBRARY_NAME}:{CELL_NAME}")
print("Reminder: manually verify Global scope is set on both VAR_Ftheta "
      "and VAR_Fphi via Component Options in the ADS GUI.")

# ---- Spot check: print one stored formula string from each VAR ----
sample_i = next(iter(ftheta_data))
sample_l, sample_m = idx_to_lm[sample_i]
sample_ftheta_name = var_name("Ftheta", sample_l, sample_m)
print(f"Spot check: {sample_ftheta_name} = {var_ftheta.vars[sample_ftheta_name]}")

sample_i2 = next(iter(fphi_data))
sample_l2, sample_m2 = idx_to_lm[sample_i2]
sample_fphi_name = var_name("Fphi", sample_l2, sample_m2)
print(f"Spot check: {sample_fphi_name} = {var_fphi.vars[sample_fphi_name]}")
